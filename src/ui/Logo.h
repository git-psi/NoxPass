    constexpr int EYE_Y0 = 6, EYE_Y1 = 14, LID_ROWS = 5;
    static const int8_t ARC[10][2] = { {6, 10}, {7, 11}, {8, 11}, {9, 11}, {10, 10}, {18, 10}, {19, 11}, {20, 11}, {21, 11}, {22, 10} };

    inline bool on(int x, int y) { return ROWS[y][x] == '1'; }

    // Draws the logo, top-left corner at (x, y), enlarged by `scale`.
    inline void draw(M5Canvas& c, int16_t x, int16_t y, uint16_t color, int scale = 1) {
        for (int j = 0; j < H; j++)
            for (int i = 0; i < W; i++)
                if (on(i, j)) c.fillRect(x + i * scale, y + j * scale, scale, scale, color);
    }

    // The same logo as SVG (one rectangle per run of pixels), for the website.
    inline String svg() {
        String s = "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 29 42' shape-rendering='crispEdges'><path d='";
        for (int j = 0; j < H; j++) {
            int i = 0;
            while (i < W) {
                if (!on(i, j)) { i++; continue; }
                int e = i;
                while (e < W && on(e, j)) e++;
                s += "M"; s += i; s += " "; s += j; s += "h"; s += (e - i); s += "v1h-"; s += (e - i); s += "z";
                i = e;
            }
        }
        s += "'/></svg>";
        return s;
    }

    // Logo with eyes closed at `closed` / 255 (0 = open, 255 = closed), enlarged by `scale`.
    inline void drawClosing(M5Canvas& c, int16_t x, int16_t y, uint16_t fg, uint16_t bg, int scale, uint8_t closed) {
        draw(c, x, y, fg, scale);
        const int lid = (closed * LID_ROWS + 127) / 255;            // Rows covered by each eyelid: 0 .. LID_ROWS
        for (int j = EYE_Y0; j <= EYE_Y1; j++) {
            if (j >= EYE_Y0 + lid && j <= EYE_Y1 - lid) continue;   // Row still open
            for (int i = 0; i < W; i++)
                if (EYES[j][i] == '1') c.fillRect(x + i * scale, y + j * scale, scale, scale, fg);
        }
        if (closed == 255)                                           // Closed: a sleep arc per eye
            for (int k = 0; k < 10; k++)
                c.fillRect(x + ARC[k][0] * scale, y + ARC[k][1] * scale, scale, scale, bg);
    }
